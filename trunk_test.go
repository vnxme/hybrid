func TestTrunkWriteLLM(t *testing.T) {
	laddr := &net.UDPAddr{IP: net.IPv4(127, 0, 0, 1), Port: 1000}
	raddr := &net.UDPAddr{IP: net.IPv4(127, 0, 0, 1), Port: 2000}

	tests := []struct {
		name       string
		setup      func(t *testing.T, trA, trB *trunk) // pre-fill close channels, set deadlines, etc.
		payloadLen int
		wantN      int
		wantErr    error
		wantErrIs  error
		checkData  bool     // if true, after success read from remote and compare original payload
		expectedR  net.Addr // expected remote addr in read packet (if checkData)
		expectedL  net.Addr // expected local addr in read packet (if checkData)
		expectedI  int      // expected index in read packet (if checkData)
	}{
		{
			name:       "NormalWriteBuffered",
			setup:      func(t *testing.T, trA, trB *trunk) {},
			payloadLen: 10,
			wantN:      10,
			wantErr:    nil,
			checkData:  true,
			expectedR:  laddr,
			expectedL:  raddr,
			expectedI:  0,
		},
		{
			name: "WriteAfterLocalClose",
			setup: func(t *testing.T, trA, trB *trunk) {
				_ = trA.Close()
			},
			payloadLen: 10,
			wantN:      0,
			wantErr:    errTrunkClosed,
		},
		{
			name: "WriteAfterRemoteClose",
			setup: func(t *testing.T, trA, trB *trunk) {
				_ = trB.Close()
			},
			payloadLen: 10,
			wantN:      0,
			wantErr:    errTrunkClosed,
		},
		{
			name: "WriteDeadlineExceeded",
			setup: func(t *testing.T, trA, trB *trunk) {
				_ = trA.SetWriteDeadline(time.Now().Add(-time.Hour))
			},
			payloadLen: 10,
			wantN:      0,
			wantErr:    errTrunkDeadlineExceeded,
		},
		{
			name: "WriteDeadlineExceededRemoteClosed",
			setup: func(t *testing.T, trA, trB *trunk) {
				_ = trA.SetWriteDeadline(time.Now().Add(-time.Hour))
				_ = trB.Close()
			},
			payloadLen: 10,
			wantN:      0,
			wantErr:    errTrunkClosed,
		},
		{
			name: "WriteBlockingThenLocalClose",
			setup: func(t *testing.T, trA, trB *trunk) {
				// Fill the write buffer (capacity 1) so next write will block.
				trA.wrTx <- trunkPacket{b: []byte("fill"), src: nil, dst: nil, i: 0}
				// Then schedule a close to unblock.
				go func() {
					time.Sleep(10 * time.Millisecond)
					_ = trB.Close()
				}()
			},
			payloadLen: 10,
			wantN:      0,
			wantErr:    errTrunkClosed,
		},
		{
			name: "WriteBlockingThenWriteDeadline",
			setup: func(t *testing.T, trA, trB *trunk) {
				trA.wrTx <- trunkPacket{b: []byte("fill"), src: nil, dst: nil, i: 0}
				_ = trA.SetWriteDeadline(time.Now().Add(50 * time.Millisecond))
			},
			payloadLen: 10,
			wantN:      0,
			wantErr:    errTrunkDeadlineExceeded,
		},
		{
			name: "WriteUnbufferedBlockingThenRemoteClose",
			setup: func(t *testing.T, trA, trB *trunk) {
				// Use unbuffered: close remote to unblock the write.
				go func() {
					time.Sleep(10 * time.Millisecond)
					_ = trB.Close()
				}()
			},
			payloadLen: 5,
			wantN:      0,
			wantErr:    errTrunkClosed,
		},
		{
			name: "CloneOnBufferedWrite",
			setup: func(t *testing.T, trA, trB *trunk) {
				// No special setup; we will verify data integrity later.
			},
			payloadLen: 5,
			wantN:      5,
			wantErr:    nil,
			checkData:  true,
			expectedR:  laddr,
			expectedL:  raddr,
			expectedI:  1,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// Use buffered trunk with capacity 1 by default; for unbuffered tests we explicitly create them.
			var spcA, spcB SelectivePacketConn
			if tt.name == "WriteUnbufferedBlockingThenRemoteClose" {
				spcA, spcB = UnbufferedTrunk(nil, nil)
			} else {
				spcA, spcB = BufferedTrunk(1, nil, nil)
			}
			trA := spcA.(*trunk)
			trB := spcB.(*trunk)

			tt.setup(t, trA, trB)

			payload := make([]byte, tt.payloadLen)
			// fill payload with non-zero bytes
			for i := range payload {
				payload[i] = byte(i + 1)
			}

			n, err := trA.write(payload, raddr, laddr, tt.expectedI)

			if n != tt.wantN {
				t.Errorf("write() n = %d, want %d", n, tt.wantN)
			}
			if tt.wantErr != nil {
				if err == nil {
					t.Errorf("write() error = nil, want %v", tt.wantErr)
				} else if tt.wantErrIs != nil {
					if !errors.Is(err, tt.wantErrIs) {
						t.Errorf("write() error = %v, want error is %v", err, tt.wantErrIs)
					}
				} else if !errors.Is(err, tt.wantErr) {
					t.Errorf("write() error = %v, want %v", err, tt.wantErr)
				}
			} else if err != nil {
				t.Errorf("write() error = %v, want nil", err)
			}

			if tt.checkData && err == nil {
				// Verify data was transmitted correctly by reading from the remote side.
				buf := make([]byte, tt.payloadLen+10)
				_ = trB.SetReadDeadline(time.Now().Add(50 * time.Millisecond))
				m, r, l, i, errRead := trB.read(buf)
				if errRead != nil {
					t.Fatalf("read() after write returned error: %v", errRead)
				}
				if m != tt.payloadLen {
					t.Errorf("read() n = %d, want %d", m, tt.payloadLen)
				}
				if !bytes.Equal(buf[:m], payload) {
					t.Error("read() data mismatch with original payload")
				}
				if !equalNetAddr(r, tt.expectedR) {
					t.Errorf("read() remote addr = %v, want %v", r, tt.expectedR)
				}
				if !equalNetAddr(l, tt.expectedL) {
					t.Errorf("read() local addr = %v, want %v", l, tt.expectedL)
				}
				if i != tt.expectedI {
					t.Errorf("read() index = %d, want %d", i, tt.expectedI)
				}

				// For the clone test, also verify that modifying the original payload does not affect the received data.
				if tt.name == "CloneOnBufferedWrite" {
					payload[0] = 0xFF // modify original
					buf2 := make([]byte, tt.payloadLen+10)
					_ = trB.SetReadDeadline(time.Now().Add(50 * time.Millisecond))
					m2, _, _, _, errRead2 := trB.read(buf2)
					if errRead2 == nil && m2 > 0 {
						t.Errorf("read() got extra data after modification, expected channel empty")
					}
				}
			}

			_ = spcA.Close()
			_ = spcB.Close()
		})
	}
}

// TestTrunkCloseLLM is generated by deepseek-v4-flash
// in JetBrains GoLand 2026.1.1 via AI Actions -> Generate Unit Tests
func TestTrunkCloseLLM(t *testing.T) {
	t.Run("Table", func(t *testing.T) {
		tests := []struct {
			name       string
			setup      func(t *testing.T, trA, trB *trunk)
			wantErrors []error // expected errors for successive Close() calls (nil means no error)
		}{
			{
				name:       "Once",
				setup:      nil,
				wantErrors: []error{nil},
			},
			{
				name:       "Twice",
				setup:      nil,
				wantErrors: []error{nil, errTrunkClosed},
			},
			{
				name: "AfterRemoteClose",
				setup: func(t *testing.T, trA, trB *trunk) {
					_ = trB.Close()
				},
				wantErrors: []error{nil, errTrunkClosed},
			},
			{
				name:       "UnbufferedOnce",
				setup:      nil, // will create unbuffered trunk
				wantErrors: []error{nil},
			},
		}

		for _, tt := range tests {
			t.Run(tt.name, func(t *testing.T) {
				var spcA, spcB SelectivePacketConn
				if tt.name == "UnbufferedOnce" {
					spcA, spcB = UnbufferedTrunk(nil, nil)
				} else {
					spcA, spcB = BufferedTrunk(1, nil, nil)
				}
				trA := spcA.(*trunk)
				trB := spcB.(*trunk)

				if tt.setup != nil {
					tt.setup(t, trA, trB)
				}

				for i, wantErr := range tt.wantErrors {
					err := trA.Close()
					if (err == nil) != (wantErr == nil) {
						t.Errorf("Close() call %d: error = %v, want %v", i+1, err, wantErr)
					} else if err != nil && !errors.Is(err, wantErr) {
						t.Errorf("Close() call %d: error = %v, want %v", i+1, err, wantErr)
					}
				}

				_ = spcB.Close()
			})
		}
	})

	t.Run("Concurrent", func(t *testing.T) {
		spcA, spcB := BufferedTrunk(1, nil, nil)
		trA := spcA.(*trunk)
		defer func() { _ = spcB.Close() }()

		const goroutines = 20
		errCh := make(chan error, goroutines)
		var wg sync.WaitGroup
		wg.Add(goroutines)
		for i := 0; i < goroutines; i++ {
			go func() {
				defer wg.Done()
				errCh <- trA.Close()
			}()
		}
		wg.Wait()
		close(errCh)

		nilCount := 0
		errCount := 0
		for err := range errCh {
			if err == nil {
				nilCount++
			} else if errors.Is(err, errTrunkClosed) {
				errCount++
			} else {
				t.Errorf("unexpected error: %v", err)
			}
		}
		if nilCount != 1 {
			t.Errorf("Close() succeeded %d times, want exactly 1", nilCount)
		}
		if errCount != goroutines-1 {
			t.Errorf("Close() returned errTrunkClosed %d times, want %d", errCount, goroutines-1)
		}
	})
}

// TestTrunkSliceAlias ensures a trunk doesn't refer to a write buffer once the write has returned,
// so that the caller may reuse it right away, as UDP code commonly does. A regression is likely,
// though not certain, to be detected, as it depends on how reads and writes are scheduled.
func TestTrunkSliceAlias(t *testing.T) {
	for name, ctor := range map[string]func() (SelectivePacketConn, SelectivePacketConn){
		"Unbuffered": func() (SelectivePacketConn, SelectivePacketConn) { return UnbufferedTrunk(nil, nil) },
		"Buffered":   func() (SelectivePacketConn, SelectivePacketConn) { return BufferedTrunk(10, nil, nil) },
	} {
		t.Run(name, func(t *testing.T) {
			c1, c2 := ctor()
			const packets, size = 1 << 10, 1 << 16

			var wg sync.WaitGroup
			wg.Go(func() {
				b := make([]byte, size)
				for range packets {
					clear(b)
					if _, err := c1.WriteTo(b, nil); err != nil {
						t.Errorf("c1.WriteTo() = %v, want nil", err)
						return
					}
					for i := range b {
						b[i] = 0xff
					}
				}
			})

			b := make([]byte, size)
			for i := range packets {
				_ = c2.SetReadDeadline(time.Now().Add(time.Second))
				n, _, err := c2.ReadFrom(b)
				if err != nil {
					t.Errorf("c2.ReadFrom() = %v, want nil", err)
					break
				}
				if bytes.IndexByte(b[:n], 0xff) >= 0 {
					t.Errorf("packet %d is modified after its write has returned", i)
					break
				}
			}

			_ = c2.Close()
			_ = c1.Close()
			wg.Wait()
		})
	}
}

// TestTrunkAddrs ensures each end of a trunk has its own local address used by default,
// and multiple packet flows sharing a trunk are told apart by addresses.
func TestTrunkAddrs(t *testing.T) {
	addr1 := &net.UDPAddr{IP: net.IPv4(10, 0, 0, 1), Port: 53}
	addr2 := &net.UDPAddr{IP: net.IPv4(10, 0, 0, 2), Port: 53}
	flow1 := &net.UDPAddr{IP: net.IPv4(192, 0, 2, 1), Port: 1001}
	flow2 := &net.UDPAddr{IP: net.IPv4(192, 0, 2, 2), Port: 1002}

	t.Run("Default", func(t *testing.T) {
		c1, c2 := BufferedTrunk(1, nil, nil)
		defer func() {
			_ = c1.Close()
			_ = c2.Close()
		}()
		for name, addr := range map[string]net.Addr{"c1": c1.LocalAddr(), "c2": c2.LocalAddr()} {
			if addr == nil || addr.Network() != trunkNetwork {
				t.Errorf("%s.LocalAddr() = %v, want a %s address", name, addr, trunkNetwork)
			}
		}
	})

	c1, c2 := BufferedTrunk(4, addr1, addr2)
	defer func() {
		_ = c1.Close()
		_ = c2.Close()
	}()
	if got := c1.LocalAddr(); got != addr1 {
		t.Errorf("c1.LocalAddr() = %v, want %v", got, addr1)
	}
	if got := c2.LocalAddr(); got != addr2 {
		t.Errorf("c2.LocalAddr() = %v, want %v", got, addr2)
	}

	// expect reads a packet from c and checks its payload, addresses and interface index
	expect := func(c SelectivePacketConn, payload string, src, dst net.Addr, idx int) {
		t.Helper()
		_ = c.SetReadDeadline(time.Now().Add(time.Second))
		b := make([]byte, 16)
		n, gotSrc, gotDst, gotIdx, err := c.ReadFromTo(b)
		if err != nil || string(b[:n]) != payload || gotSrc != src || gotDst != dst || gotIdx != idx {
			t.Errorf("ReadFromTo() = %q, %v, %v, %d, %v, want %q, %v, %v, %d, nil",
				b[:n], gotSrc, gotDst, gotIdx, err, payload, src, dst, idx)
		}
	}

	// Without addresses, a packet goes from one local address to the other
	_, _ = c1.WriteTo([]byte("a"), nil)
	expect(c2, "a", addr1, addr2, 0)

	// Interleaved flows keep their addresses and interface indices
	_, _ = c1.WriteToFrom([]byte("b"), addr2, flow1, 1)
	_, _ = c1.WriteToFrom([]byte("c"), addr2, flow2, 2)
	_, _ = c1.WriteToFrom([]byte("d"), addr2, flow1, 1)
	expect(c2, "b", flow1, addr2, 1)
	expect(c2, "c", flow2, addr2, 2)
	expect(c2, "d", flow1, addr2, 1)

	// A reply by means of PacketConn reaches the flow it is addressed to
	_, _ = c2.WriteTo([]byte("e"), flow2)
	expect(c1, "e", addr2, flow2, 0)

	// No addresses are returned on errors
	_ = c2.SetReadDeadline(time.Now().Add(-time.Second))
	if _, src, dst, _, err := c2.ReadFromTo(make([]byte, 16)); err == nil || src != nil || dst != nil {
		t.Errorf("ReadFromTo() = %v, %v, %v, want nil, nil, an error", src, dst, err)
	}
}

// TestTrunkConcurrent ensures concurrent writers and readers neither lose, duplicate nor corrupt
// packets, while every writer reuses its buffer right after a write has returned.
func TestTrunkConcurrent(t *testing.T) {
	for name, ctor := range map[string]func() (SelectivePacketConn, SelectivePacketConn){
		"Unbuffered": func() (SelectivePacketConn, SelectivePacketConn) { return UnbufferedTrunk(nil, nil) },
		"Buffered":   func() (SelectivePacketConn, SelectivePacketConn) { return BufferedTrunk(10, nil, nil) },
	} {
		t.Run(name, func(t *testing.T) {
			c1, c2 := ctor()
			const writers, readers, packets, size = 4, 4, 1 << 8, 1 << 12

			// A packet starts with its writer and sequence numbers followed by the latter repeated
			var wwg sync.WaitGroup
			for w := range writers {
				wwg.Go(func() {
					b := make([]byte, size)
					for seq := range packets {
						b[0] = byte(w)
						for i := 1; i < size; i++ {
							b[i] = byte(seq)
						}
						if _, err := c1.WriteTo(b, nil); err != nil {
							t.Errorf("c1.WriteTo() = %v, want nil", err)
							return
						}
						clear(b)
					}
				})
			}

			var mu sync.Mutex
			seen := make(map[[2]byte]bool)
			var rwg sync.WaitGroup
			for range readers {
				rwg.Go(func() {
					b := make([]byte, size)
					for {
						_ = c2.SetReadDeadline(time.Now().Add(deadlineQuiet))
						n, _, err := c2.ReadFrom(b)
						if errors.Is(err, os.ErrDeadlineExceeded) {
							return // All packets have been read
						}
						if err != nil || n != size || bytes.Count(b[1:n], b[1:2]) != n-1 {
							t.Errorf("c2.ReadFrom() = %d, %v, want an intact packet of %d bytes", n, err, size)
							return
						}
						key := [2]byte{b[0], b[1]}
						mu.Lock()
						if seen[key] {
							t.Errorf("packet %v is read twice", key)
						}
						seen[key] = true
						mu.Unlock()
					}
				})
			}

			wwg.Wait()
			rwg.Wait()
			if len(seen) != writers*packets {
				t.Errorf("read %d packets, want %d", len(seen), writers*packets)
			}
			_ = c1.Close()
			_ = c2.Close()
		})
	}
}
